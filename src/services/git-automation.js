const { info, warn, error } = require('./logger');
/**
 * Git Automation Service
 * Provides autonomous Git workflow with progress commits every 30 minutes
 * Part of Phase 2 Task 2.3: Git Automation Pipeline
 */

const { exec } = require('child_process');
const { promisify } = require('util');
const path = require('path');
const fs = require('fs').promises;
const { v4: uuidv4 } = require('uuid');

const execAsync = promisify(exec);

class GitAutomation {
    constructor(config = {}) {
        this.config = {
            repositoryPath: config.repositoryPath || process.cwd(),
            commitInterval: config.commitInterval || 30 * 60 * 1000, // 30 minutes
            branchPrefix: config.branchPrefix || 'autonomous-execution',
            enableAutoCommit: config.enableAutoCommit !== false,
            enableAutoPush: config.enableAutoPush !== false,
            remoteOrigin: config.remoteOrigin || 'origin',
            ...config
        };
        
        // Git automation state
        this.currentBranch = null;
        this.baseBranch = null;
        this.workflowBranch = null;
        this.commitHistory = [];
        this.autoCommitTimer = null;
        
        // Commit tracking
        this.lastCommitHash = null;
        this.uncommittedChanges = [];
        
        info(` Git Automation initialized for: ${this.config.repositoryPath}`);
    }
    
    /**
     * Initialize Git automation for autonomous execution
     */
    async initialize() {
        try {
            // Check if we're in a git repository
            await this.validateGitRepository();
            
            // Get current branch
            this.baseBranch = await this.getCurrentBranch();
            this.currentBranch = this.baseBranch;
            
            info(` Base branch: ${this.baseBranch}`);
            
            // Check for uncommitted changes
            await this.checkUncommittedChanges();
            
            info('Git automation initialized successfully');
            
        } catch (error) {
            error('FAIL Git automation initialization failed:', error.message);
            throw error;
        }
    }
    
    /**
     * Create autonomous workflow branch
     */
    async createWorkflowBranch(sessionId, branchName = null) {
        try {
            const timestamp = new Date().toISOString().replace(/[:.]/g, '-').split('T')[0];
            this.workflowBranch = branchName || `${this.config.branchPrefix}-${sessionId}-${timestamp}`;
            
            info(` Creating workflow branch: ${this.workflowBranch}`);
            
            // Create and switch to new branch
            await this.execGitCommand(`checkout -b ${this.workflowBranch}`);
            this.currentBranch = this.workflowBranch;
            
            // Create initial commit for the workflow
            await this.commitProgress('Initialize autonomous execution workflow', [], true);
            
            // Push branch to remote if enabled
            if (this.config.enableAutoPush) {
                await this.pushBranch(this.workflowBranch);
            }
            
            info(`Workflow branch created: ${this.workflowBranch}`);

            const validation = { success: this.validateSuccess() };return {

                success: validation.success,
                branchName: this.workflowBranch,
                baseBranch: this.baseBranch,
                initialCommit: this.lastCommitHash
            };
            
        } catch (error) {
            error('FAIL Failed to create workflow branch:', error.message);
            throw error;
        }
    }
    
    /**
     * Commit progress automatically
     */
    async commitProgress(message, files = [], force = false) {
        try {
            // Check if there are changes to commit
            const hasChanges = await this.hasUncommittedChanges();
            if (!hasChanges && !force) {
                info(' No changes to commit');

                const validation = { success: this.validateSuccess() };return {

                    success: validation.success,
                    message: 'No changes to commit',
                    commitHash: this.lastCommitHash
                };
            }
            
            info(` Committing progress: ${message}`);
            
            // Stage files
            if (files.length > 0) {
                for (const file of files) {
                    await this.execGitCommand(`add "${file}"`);
                }
            } else {
                // Stage all changes
                await this.execGitCommand('add -A');
            }
            
            // Create commit with timestamp
            const timestamp = new Date().toISOString();
            const fullMessage = `${message}
            
Autonomous Execution Progress
Timestamp: ${timestamp}
Branch: ${this.currentBranch}
Session: ${this.getSessionFromBranch()}

AGENT Generated by LonicFLex Autonomous Execution Service`;
            
            const commitResult = await this.execGitCommand(`commit -m "${fullMessage}"`);
            
            // Get the commit hash
            this.lastCommitHash = await this.getLastCommitHash();
            
            // Track commit
            this.commitHistory.push({
                hash: this.lastCommitHash,
                message: message,
                timestamp: Date.now(),
                files: files.length > 0 ? files : ['all changes']
            });
            
            info(`Progress committed: ${this.lastCommitHash.substring(0, 8)}`);
            
            // Push if enabled
            if (this.config.enableAutoPush) {
                await this.pushBranch(this.currentBranch);
            }

            const validation = { success: this.validateSuccess() };return {

                success: validation.success,
                commitHash: this.lastCommitHash,
                message: message,
                timestamp: timestamp
            };
            
        } catch (error) {
            error('FAIL Failed to commit progress:', error.message);
            throw error;
        }
    }
    
    /**
     * Start automatic commit timer
     */
    startAutoCommit() {
        if (this.autoCommitTimer) {
            info('CYCLE Auto-commit already running');
            return;
        }
        
        info(`CLOCK Starting auto-commit every ${this.config.commitInterval / 60000} minutes`);
        
        this.autoCommitTimer = setInterval(async () => {
            try {
                await this.commitProgress(`Automatic progress commit - ${new Date().toLocaleTimeString()}`);
            } catch (error) {
                error('FAIL Auto-commit failed:', error.message);
            }
        }, this.config.commitInterval);
    }
    
    /**
     * Stop automatic commit timer
     */
    stopAutoCommit() {
        if (this.autoCommitTimer) {
            clearInterval(this.autoCommitTimer);
            this.autoCommitTimer = null;
            info(' Auto-commit stopped');
        }
    }
    
    /**
     * Rollback to a specific commit
     */
    async rollbackToCommit(commitHash) {
        try {
            info(`CYCLE Rolling back to commit: ${commitHash}`);
            
            // Hard reset to the specified commit
            await this.execGitCommand(`reset --hard ${commitHash}`);
            
            // Update tracking
            this.lastCommitHash = commitHash;
            
            // If we're on a remote branch, force push the rollback
            if (this.config.enableAutoPush) {
                await this.execGitCommand(`push --force-with-lease ${this.config.remoteOrigin} ${this.currentBranch}`);
            }
            
            info(`Rolled back to commit: ${commitHash}`);

            const validation = { success: this.validateSuccess() };return {

                success: validation.success,
                commitHash: commitHash,
                branch: this.currentBranch,
                rolledBackAt: Date.now()
            };
            
        } catch (error) {
            error('FAIL Rollback failed:', error.message);
            throw error;
        }
    }
    
    /**
     * Push branch to remote
     */
    async pushBranch(branchName = null) {
        try {
            const branch = branchName || this.currentBranch;
            info(` Pushing branch: ${branch}`);
            
            // Push branch with upstream tracking
            await this.execGitCommand(`push -u ${this.config.remoteOrigin} ${branch}`);
            
            info(`Branch pushed: ${branch}`);

            const validation = { success: this.validateSuccess() };return {

                success: validation.success,
                branch: branch,
                remote: this.config.remoteOrigin
            };
            
        } catch (error) {
            // Don't fail if push fails (might be working offline)
            console.warn('WARN Push failed (working offline?):', error.message);
            return {
                success: false,
                error: error.message,
                branch: branchName || this.currentBranch
            };
        }
    }
    
    /**
     * Create pull request (if supported)
     */
    async createPullRequest(title, description = '', targetBranch = null) {
        try {
            const target = targetBranch || this.baseBranch;
            
            info(`Creating pull request: ${this.currentBranch} -> ${target}`);
            
            // This would integrate with GitHub/GitLab APIs
            // For now, just return the information needed
            const prInfo = {
                sourceBranch: this.currentBranch,
                targetBranch: target,
                title: title,
                description: description || `Autonomous execution results from ${this.currentBranch}
                
## Autonomous Execution Summary

Branch: ${this.currentBranch}
Commits: ${this.commitHistory.length}
Base Branch: ${this.baseBranch}

## Commit History
${this.commitHistory.map(c => `- ${c.hash.substring(0, 8)}: ${c.message}`).join('\n')}

AGENT Generated by LonicFLex Autonomous Execution Service`,
                commits: this.commitHistory.length,
                url: null // Would be populated by actual API integration
            };
            
            info(`Pull request prepared: ${title}`);
            return prInfo;
            
        } catch (error) {
            error('FAIL Failed to create pull request:', error.message);
            throw error;
        }
    }
    
    /**
     * Switch back to base branch
     */
    async switchToBaseBranch() {
        try {
            if (this.currentBranch === this.baseBranch) {
                info(` Already on base branch: ${this.baseBranch}`);
                return;
            }
            
            info(`CYCLE Switching to base branch: ${this.baseBranch}`);
            
            // Check for uncommitted changes
            const hasChanges = await this.hasUncommittedChanges();
            if (hasChanges) {
                throw new Error('Cannot switch branches: uncommitted changes detected');
            }
            
            await this.execGitCommand(`checkout ${this.baseBranch}`);
            this.currentBranch = this.baseBranch;
            
            info(`Switched to base branch: ${this.baseBranch}`);
            
        } catch (error) {
            error('FAIL Failed to switch to base branch:', error.message);
            throw error;
        }
    }
    
    /**
     * Clean up workflow branch
     */
    async cleanupWorkflowBranch(deleteRemote = false) {
        try {
            if (!this.workflowBranch) {
                info('CLEANUP No workflow branch to clean up');
                return;
            }
            
            info(`CLEANUP Cleaning up workflow branch: ${this.workflowBranch}`);
            
            // Switch to base branch first
            await this.switchToBaseBranch();
            
            // Delete local branch
            await this.execGitCommand(`branch -D ${this.workflowBranch}`);
            
            // Delete remote branch if requested
            if (deleteRemote) {
                try {
                    await this.execGitCommand(`push ${this.config.remoteOrigin} --delete ${this.workflowBranch}`);
                    info(`DELETE Remote branch deleted: ${this.workflowBranch}`);
                } catch (error) {
                    console.warn('WARN Failed to delete remote branch:', error.message);
                }
            }
            
            info(`Workflow branch cleaned up: ${this.workflowBranch}`);
            this.workflowBranch = null;
            
        } catch (error) {
            error('FAIL Cleanup failed:', error.message);
            throw error;
        }
    }
    
    /**
     * Get Git status information
     */
    async getStatus() {
        try {
            const statusOutput = await this.execGitCommand('status --porcelain');
            const branchInfo = await this.execGitCommand('branch --show-current');
            
            return {
                currentBranch: this.currentBranch,
                baseBranch: this.baseBranch,
                workflowBranch: this.workflowBranch,
                lastCommitHash: this.lastCommitHash,
                uncommittedFiles: statusOutput.stdout.split('\n').filter(line => line.trim()),
                commitHistory: this.commitHistory,
                autoCommitEnabled: !!this.autoCommitTimer
            };
            
        } catch (error) {
            error('FAIL Failed to get Git status:', error.message);
            throw error;
        }
    }
    
    /**
     * Helper methods
     */
    async validateGitRepository() {
        try {
            await this.execGitCommand('rev-parse --git-dir');
        } catch (error) {
            throw new Error(`Not a Git repository: ${this.config.repositoryPath}`);
        }
    }
    
    async getCurrentBranch() {
        const result = await this.execGitCommand('branch --show-current');
        return result.stdout.trim();
    }
    
    async hasUncommittedChanges() {
        const result = await this.execGitCommand('status --porcelain');
        return result.stdout.trim().length > 0;
    }
    
    async checkUncommittedChanges() {
        const hasChanges = await this.hasUncommittedChanges();
        if (hasChanges) {
            const statusOutput = await this.execGitCommand('status --porcelain');
            this.uncommittedChanges = statusOutput.stdout.split('\n').filter(line => line.trim());
            warn(`Found ${this.uncommittedChanges.length} uncommitted changes`);
        }
    }
    
    async getLastCommitHash() {
        const result = await this.execGitCommand('rev-parse HEAD');
        return result.stdout.trim();
    }
    
    getSessionFromBranch() {
        if (this.workflowBranch && this.workflowBranch.includes('-')) {
            const parts = this.workflowBranch.split('-');
            return parts.length >= 3 ? parts.slice(2, -1).join('-') : 'unknown';
        }
        return 'unknown';
    }
    
    async execGitCommand(command) {
        const fullCommand = `git ${command}`;
        logger.debug(`Git: ${fullCommand}`);
        
        try {
            const result = await execAsync(fullCommand, {
                cwd: this.config.repositoryPath,
                timeout: 30000 // 30 second timeout
            });
            
            return result;
        } catch (error) {
            error(`FAIL Git command failed: ${fullCommand}`);
            throw error;
        }
    }
    
    /**
     * Stop all Git automation processes
     */
    async stop() {
        info('STOP Stopping Git automation...');
        
        // Stop auto-commit timer
        this.stopAutoCommit();
        
        // Final commit if there are changes
        try {
            const hasChanges = await this.hasUncommittedChanges();
            if (hasChanges) {
                await this.commitProgress('Final autonomous execution commit');
            }
        } catch (error) {
            error('FAIL Final commit failed:', error.message);
        }
        
        info('Git automation stopped');
    }
}

module.exports = { GitAutomation };

